const initialLocale = (): Locale => {
  if (typeof window === "undefined") return "es";
  const requested = new URLSearchParams(window.location.search).get("lang");
  if (requested === "es" || requested === "en") return requested;
  try {
    const saved = localStorage.getItem("inkgroove:locale");
    if (saved === "es" || saved === "en") return saved;
  } catch { /* A blocked preference store must not block writing. */ }
  return document.documentElement.lang === "en" ? "en" : "es";
};
let locale = initialLocale();
const listeners = new Set<() => void>();
export const getLocale = () => locale;
export const t = (message: string, values: Record<string, string | number> = {}, language = locale) =>
  (language === "en" ? EN[message] ?? message : message).replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token));

const applyLocale = () => {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  try { document.cookie = `inkgroove_locale=${locale}; Path=/; Max-Age=31536000; SameSite=Lax${window.location.protocol === "https:" ? "; Secure" : ""}`; } catch { /* Language remains usable when cookies are blocked. */ }
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("Conserva el proceso de escritura, vuelve sobre tus borradores y comparte las versiones que tú elijas."));
};
applyLocale();
export const setLocale = (next: Locale) => {
  if (next !== "es" && next !== "en") return;
  locale = next;
  try { localStorage.setItem("inkgroove:locale", next); } catch { /* Preference remains usable for this session. */ }
  applyLocale();
  if (typeof window !== "undefined") {
    const url = new URL(window.location.href);
    if (url.searchParams.has("lang")) { url.searchParams.set("lang", next); window.history.replaceState(null, "", url); }
  }
  listeners.forEach(listener => listener());
};
export const useLocale = () => useSyncExternalStore(listener => { listeners.add(listener); return () => listeners.delete(listener); }, getLocale, () => "es" as Locale);
